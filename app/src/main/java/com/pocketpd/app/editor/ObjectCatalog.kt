    /**
     * Ranked search: exact prefix first, then word-boundary match, then any
     * substring. Symbols like "+~" only ever match by prefix.
     */
    fun search(query: String, limit: Int = 10): List<Entry> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return entries.take(limit)
        val prefix = mutableListOf<Entry>()
        val word = mutableListOf<Entry>()
        val contains = mutableListOf<Entry>()
        for (e in entries) {
            val n = e.name.lowercase()
            if (n.startsWith(q)) prefix.add(e)
            else if (n.contains(q)) {
                // word-boundary: "~", "-" etc. separate name parts
                val idx = n.indexOf(q)
                val sepBefore = idx == 0 || !n[idx - 1].isLetterOrDigit()
                if (sepBefore) word.add(e) else contains.add(e)
            }
        }
        return (prefix + word + contains).take(limit)
    }

    /** Hint for the top match of a query, or null when nothing matches. */
    fun topHint(query: String): Entry? = search(query, 1).firstOrNull()
