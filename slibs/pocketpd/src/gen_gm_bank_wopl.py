#!/usr/bin/env python3
"""Regenerates opl_gm_bank.h from archive/mobilnik-v2.wopl.

Source bank: Mobilnik-v2.wopl (WOPL v3, melodic bank 0, GM order 1-128),
by Vitaliy Novichkov "Wohlstand", MIT license (with the original The Fat
Man OPL instrument set, MIT, github.com/Wohlstand/TheFatManOPL) - the
OPL3-flavored General MIDI set distributed with OPL3BankEditor
(Bank_Examples/Mobilnik-v2.wopl + Mobilnik-v2-readme.txt).

The bank entries are RAW OPL REGISTER BYTES, so the struct keeps them
verbatim - the `gm` message dumps them 1:1 into the addressed channel:
  op[c][0..4] = registers 0x20/0x40/0x60/0x80/0xE0 of the operator,
                c 0 = carrier (op1), c 1 = modulator (op2)
  fbconn      = feedback/connection byte (bit0 CON, bits 1-3 FB) - the
                C0 register value minus the pan bits
  tr          = semitone transpose (WOPL BE16 note offset, byte 32-33)
This bank is 100% 2-op (no 4-op/pseudo-4op/blank flags anywhere), so a
single-voice dump covers every preset; the WOPL operator order is
op1=carrier, op2=modulator (spec section 1).
"""
import struct, sys

SRC = r"C:\Projects\26PDAndroid\archive\mobilnik-v2.wopl"
OUT = r"C:\Projects\26PDAndroid\slibs\pocketpd\src\opl_gm_bank.h"

d = open(SRC, "rb").read()
if d[:11] != b"WOPL3-BANK\x00":
    sys.exit("not a WOPL bank")
ver = struct.unpack("<H", d[11:13])[0]
mbanks = struct.unpack(">H", d[13:15])[0]
pbanks = struct.unpack(">H", d[15:17])[0]
insz = 66 if ver >= 3 else 62
base = 19 + (34 * (mbanks + pbanks) if ver >= 2 else 0)
if len(d) < base + insz * 128 * mbanks:
    sys.exit("truncated bank")

rows = []
for n in range(128):
    e = d[base + n * insz: base + (n + 1) * insz]
    tr = struct.unpack(">h", e[32:34])[0]
    fl = e[39]
    if fl & 7:
        sys.exit("preset %d has 4op/pseudo/blank flags - generator assumes 2-op" % (n + 1))
    # entry fields: 32 name + 2+2 note offsets + 1 vel + 1 detune + 1 perc
    # key + 1 flags(39) + 1 fbconn(40) + 1 fbconn2(41) -> operators at 42;
    # WOPL operator order: op1 = carrier, op2 = modulator; 5 raw bytes each
    car = e[42:47]
    mod = e[47:52]
    fbconn = e[40]
    rows.append((car, mod, fbconn, tr))

with open(OUT, "w", newline="\n") as f:
    f.write("""/* opl3~ - GENERATED by slibs/pocketpd/src/gen_gm_bank_wopl.py, do not
 * hand-edit; regenerate instead.  Source: the Mobilnik-v2 General MIDI
 * bank (WOPL v3, melodic bank 0, GM order 1-128), by Vitaliy Novichkov
 * "Wohlstand" - MIT license - an OPL3-flavored GM set in the lineage of
 * The Fat Man's 1993 OPL instruments (K. Weston Phelan / George Alistair
 * Sanger, MIT, github.com/Wohlstand/TheFatManOPL), distributed with
 * OPL3BankEditor (Bank_Examples/Mobilnik-v2.wopl, mirrored at
 * archive/mobilnik-v2.wopl).
 *
 * Every field below is a VERBATIM OPL register byte from the bank:
 *   op[c][0..4] = registers 0x20/0x40/0x60/0x80/0xE0 of operator c
 *                 (c 0 = carrier, c 1 = modulator)
 *   fbconn      = C0 feedback/connection byte (bit0 CON, bits 1-3 FB)
 *   tr          = per-preset semitone transpose (WOPL note offset)
 * The bank is 100% 2-op (no 4-op/pseudo-4op flags), so one voice dump
 * covers every preset.  tl/sl are ATTENUATIONS (0 loudest); rate fields
 * are 0-15 (OPL is 4-bit rates, unlike the YM2612's 5/6-bit ones).
 */

typedef struct {
    unsigned char op[2][5];      /* carrier, modulator x {20 40 60 80 e0} */
    unsigned char fbconn;        /* C0 bits 0-3 */
    signed char   tr;            /* semitones */
} opl_gmpatch;

static const opl_gmpatch opl_gm_bank[128] = {
""")
    for n, (car, mod, fbconn, tr) in enumerate(rows):
        f.write("    /* GM %d */\n" % (n + 1))
        f.write("    {{{%s}, {%s}}, 0x%02x, %d},\n"
                % (", ".join("0x%02x" % b for b in car),
                   ", ".join("0x%02x" % b for b in mod),
                   fbconn, tr))
    f.write("};\n")
print("opl_gm_bank.h written: 128 presets, transpose range %d..%d"
      % (min(r[3] for r in rows), max(r[3] for r in rows)))
