#!/usr/bin/env python3
"""Generate slibs/pocketpd/src/ym_gm_bank.h from the FMTowns GM bank
(archive/fmtowns.wopn, WOPN v2, melodic bank 0 = GM order 1-128).
Provenance: distributed with libOPNMIDI (github.com/Wohlstand/libOPNMIDI,
fm_banks/FMTowns.wopn + FMTowns-readme.txt, mirrored in this repo at
archive/fmtowns-readme.txt).  The set is built from FM TOWNS FMB
instrument banks (Euphony tracker modules, modland.com) - instruments
designed on the real chip - published as public domain by Wohlstand;
that bank's percussion (based on xg.wopn/fmmidi.wopn) is not used here,
only the melodic GM bank.  Chosen over the previous default (xg.wopn,
still at archive/xg.wopn) by measured audit 2026-11-15: the xg set's
MULTI=0 modulators feeding integer-MULTI carrier chains painted
half-integer sidebands (the reported sawtooth texture); the FMTowns set
has the lowest such edge count of the audited candidates and rendered
correct pitch on the piano/bass anchors.

Since 0.17.50 the engine consumes RAW CHIP REGISTER VALUES - no conversion:
  alg          0-7 direct (same GPGX table)
  fb           0-7 direct (chip ladder, tap = post-envelope output)
  mul          0-15 direct (0 = x0.5)
  dt           0-7 direct = chip DT register (0-3 positive, 4-7 negative,
               magnitude = dt_tab[fnum band], applied as DT[kc]/fc * mul)
  tl           0-127 direct (chip -0.75dB/step attenuation)
  ar/dr/sr     0-31 direct (chip rate table; 0/1 = no motion)
  rr           0-15 direct (chip release index 34 + 4*rr)
  sl           0-15 direct (chip 3dB/step sustain level)
  rs           0-3 direct (rate scaling: ksr = kcode >> (3-RS))
  note_offset  -> ym_gm_tr[] (engine applies semitone transpose on pitch)
  DT2          YM2612 has no DT2 - the chip ignores it (dt2 all zero here)
  AM/SSG-EG/LFO/pan   engine has none - dropped (bank LFO flag documented)
"""
import struct

SRC = r"C:/Projects/26PDAndroid/archive/fmtowns.wopn"
DST = r"C:\Projects\26PDAndroid\slibs\pocketpd\src\ym_gm_bank.h"

d = open(SRC, "rb").read()
assert d[:11] == b"WOPN2-B2NK\x00"
ver = struct.unpack_from("<H", d, 11)[0]
nmel, nperc = struct.unpack_from(">HH", d, 13)
assert ver == 2 and nmel >= 1
off = 18 + 34 * (nmel + nperc)          # skip per-bank metadata
INST = 69

rows, trs, names = [], [], []
for n in range(128):
    b = off + n * INST
    name = d[b:b + 32].split(b"\x00")[0].decode("ascii", "replace")
    noteoff = struct.unpack_from(">h", d, b + 32)[0]
    fbalg = d[b + 35]
    alg, fb = fbalg & 7, (fbalg >> 3) & 7
    ops = []
    for l in range(4):
        o = b + 37 + l * 7
        dtmul, tl, rsatk, amdr, dt2sr, susrel = d[o:o + 6]
        ops.append((dtmul & 15, (dtmul >> 4) & 7, tl & 0x7f,
                    rsatk & 31, amdr & 31, dt2sr & 31,
                    susrel & 15, (susrel >> 4) & 15, (rsatk >> 6) & 3))
    rows.append((alg, fb, ops))
    trs.append(noteoff)
    names.append(name)

out = []
out.append("""/* ym2612~ - GENERATED by slibs/pocketpd/src/gen_gm_bank_wopn.py, do not
 * hand-edit; regenerate instead.  Source: the FMTowns General MIDI bank
 * (archive/fmtowns.wopn, WOPN v2, melodic bank 0, GM order 1-128),
 * from libOPNMIDI fm_banks/FMTowns.wopn (github.com/Wohlstand/libOPNMIDI,
 * MIT-hosted repo, bank content public domain; provenance notes at
 * fm_banks/FMTowns-readme.txt, mirrored at archive/fmtowns-readme.txt):
 * GM table built from FM TOWNS FMB instrument banks (Euphony tracker
 * modules, modland.com) - voices designed on the real chip.  Replaces
 * the libOPNMIDI XG bank (archive/xg.wopn, kept for rollback) after a
 * measured audit: the XG set's x0.5 modulators on integer-carrier
 * chains painted the reported half-integer sideband sawtooth texture.
 * Since 0.17.50 the engine takes RAW CHIP REGISTER VALUES, so
 * every field below is a verbatim byte from the bank (no scaling):
 *   op[] = {mul, det(DT reg 0-7), tl(-0.75dB/step), ar, dr, sr (rate
 *   0-31, 0/1 = no motion), rr(0-15), sl(3dB/step), rs(rate scaling 0-3)}
 * op order = WOPN file order = chip register page order: op[k] maps to
 * byte offset 4*k inside the channel's operator register group
 * (0x30/0x40/0x50/0x60/0x70/0x80 + 4*k), and the Nuked-OPN2 based
 * engine (0.17.51+) dumps these bytes 1:1 into channel 0's registers.
 * Per-preset semitone transposition (XG note_offset) lives in
 * ym_gm_tr[].  AM / SSG-EG / LFO are chip features the engine does not
 * load - dropped (AM bit forced 0, DT2 ignored by the YM2612 itself).
 * tl/sl are ATTENUATIONS (0 loudest, sl 15 = 93dB).
 */

typedef struct {
    float mul;
    unsigned char dt, tl, ar, dr, sr, rr, sl, rs;
} ym_gmspec;

typedef struct {
    unsigned char alg, fb;
    ym_gmspec op[4];
} ym_gmpatch;

static const ym_gmpatch ym_gm_bank[128] = {""")
for i, ((alg, fb, ops), name) in enumerate(zip(rows, names)):
    nm = name.lstrip("* ").replace("*/", "")[:28]
    out.append("    /* GM %d %s */" % (i + 1, nm))
    # explicit brace for op[4], SINGLE braces per element: MSVC's C
    # frontend counts "{{..}}" as two initializers (clang accepts it)
    out.append("    {%d, %d, { {%s}, {%s}, {%s}, {%s} }}," %
               (alg, fb, *[", ".join(str(x) for x in op) for op in ops]))
out.append("};\n")
out.append("/* XG note_offset per preset (semitones; applied to pitch) */")
out.append("static const signed char ym_gm_tr[128] = {")
for i in range(0, 128, 16):
    out.append("    " + ", ".join("%+d" % v for v in trs[i:i + 16]) + ",")
out.append("};")
open(DST, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("wrote %d rows + tr table (raw chip values)" % len(rows))
